// Real SQL and calendar integration, with readiness isolated behind an explicit fixture.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import pg from 'pg';
const url = new URL(process.env.DATABASE_URL ?? '');
assert.equal(url.hostname, '127.0.0.1');
assert.match(url.pathname, /^\/compliance_renewal_task_presentation_/);
const require = createRequire(import.meta.url);
const implementation = require('../dist/modules/frameworks/implementation.service.js');
const original = implementation.implementationForReview;
const { assessmentOutcomeService } = require('../dist/modules/frameworks/assessment-outcome.service.js');
const { prisma, withTenantSchema } = require('../dist/lib/prisma.js');
const access = JSON.parse(await fs.readFile(path.join(os.tmpdir(), 'compliance-presentation-20261023/ux-access.private.json'), 'utf8'));
const c = new pg.Client({ connectionString: url.href });
const owner = { ...access.roles.owner, role: 'owner' };
const reviewer = { ...access.roles.auditor, role: 'auditor' };
const checks = [];
try {
  await c.connect();
  const schema = (await c.query('SELECT schema_name FROM global.tenants WHERE id=$1', [owner.tenantId])).rows[0].schema_name;
  assert.match(schema, /^tenant_[a-f0-9]{32}$/);
  const frameworkId = (await c.query(`SELECT framework_id FROM "${schema}".controls WHERE framework_id IS NOT NULL LIMIT 1`)).rows[0].framework_id;
  const actual = await withTenantSchema(schema, tx => original(tx, frameworkId, owner));
  const fixture = { ...actual, status: 'implemented', hash: 'isolated-outcome-sql-fixture', plan: { ...actual.plan, owner_id: owner.id, submitted_by: owner.id } };
  implementation.implementationForReview = async () => fixture;
  const values = { kind: 'recorded', authority: 'Local test fixture only', reference: 'UX-OUTCOME-LOCAL', note: 'Synthetic local integration record. It is not an issued certificate or a real assurance conclusion.', issuedOn: '2026-01-01', nextReviewOn: '2027-11-01', evidenceId: access.evidenceId };
  await assessmentOutcomeService.save(schema, frameworkId, values, owner);
  checks.push('Outcome SQL insert with pinned evidence version');
  const loadOutcome = async () => (await c.query(`SELECT o.*,(e.current_version_id=o.evidence_version_id) proof_current FROM "${schema}".assessment_outcomes o LEFT JOIN "${schema}".evidence e ON e.id=o.evidence_id WHERE framework_id=$1`, [frameworkId])).rows[0];
  fixture.outcome = await loadOutcome();
  assert.equal(fixture.outcome.reviewed_by, null);
  await assert.rejects(assessmentOutcomeService.review(schema, frameworkId, owner), /different reviewer/);
  checks.push('Self review refused');
  fixture.hash = 'changed-assessment';
  await assert.rejects(assessmentOutcomeService.review(schema, frameworkId, reviewer), /need updating/);
  checks.push('Changed assessment refused');
  fixture.hash = 'isolated-outcome-sql-fixture';
  await assessmentOutcomeService.review(schema, frameworkId, reviewer);
  assert.equal((await loadOutcome()).reviewed_by, reviewer.id);
  checks.push('Independent review stored');
  const calendar = (await c.query(`SELECT * FROM "${schema}".compliance_calendar_events WHERE source_key=$1`, ['compliance:assessment_outcome:' + fixture.outcome.id])).rows;
  assert.equal(calendar.length, 1);
  assert.equal(calendar[0].assigned_to, owner.id);
  checks.push('One owned calendar follow-up created');
  await assessmentOutcomeService.save(schema, frameworkId, { ...values, note: values.note + ' Updated.' }, owner);
  assert.equal((await loadOutcome()).reviewed_by, null);
  checks.push('Updating outcome invalidates review');
  fixture.outcome = await loadOutcome();
  await assessmentOutcomeService.review(schema, frameworkId, reviewer);
  assert.equal((await c.query(`SELECT count(*)::int count FROM "${schema}".compliance_calendar_events WHERE source_key=$1`, ['compliance:assessment_outcome:' + fixture.outcome.id])).rows[0].count, 1);
  checks.push('Review retry keeps one follow-up');
  const realState = await withTenantSchema(schema, tx => original(tx, frameworkId, owner));
  assert.equal(realState.outcomeCurrent, false, 'Fixture readiness must not mark the actual incomplete assessment as finished');
  checks.push('Real assessment remains incomplete outside isolated readiness fixture');
  await fs.writeFile('../verification/design-20261030/outcome-checks.json', JSON.stringify({ passed: true, checks, readinessFixture: true, realAssessmentCompleted: false, productionWrites: false }, null, 2));
  console.log(JSON.stringify({ passed: true, checks: checks.length, readinessFixture: true, productionWrites: false }));
} finally { implementation.implementationForReview = original; await c.end(); await prisma.$disconnect(); }
